/**
 * PINAS 2026 — Philippine gazetteer used to place auto-ingested stories.
 *
 * A story is only ever published to the map if its headline or summary
 * mentions one of these places. No match → the story is skipped. This is
 * deliberate: an unplaceable story has no landmark to be, and guessing a
 * location would break the map's core promise.
 *
 * rank: 3 = landmark/institution (most specific), 2 = city, 1 = province/region.
 * Higher rank and longer alias win when several places match.
 *
 * P(id, name, area, lat, lng, rank, "alias|alias", "Wikipedia Title")
 */

